DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
# Tests explicitly supply a temporary SQLite path. Normal startup requires Supabase.
DB_PATH = None
INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)


class _SQLiteConnection:
    """Keep application SQL in PostgreSQL's parameter style for both backends."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, params=()):
        return self.connection.execute(query.replace("%s", "?"), params)


@contextmanager
def get_conn():
    if DATABASE_URL:
        if not DATABASE_URL.startswith(("postgresql://", "postgres://")):
            raise ValueError("DATABASE_URL must be a PostgreSQL connection URL")
        with psycopg.connect(
            DATABASE_URL, row_factory=dict_row, connect_timeout=10,
            sslmode="require", prepare_threshold=None,
        ) as conn:
            yield conn
        return

    if DB_PATH is None:
        raise ValueError("Set DATABASE_URL in backend/.env to your Supabase PostgreSQL URL")
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        yield _SQLiteConnection(conn)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _column_names(conn, table):
    if isinstance(conn, _SQLiteConnection):
        return {row["name"] for row in conn.execute(f"PRAGMA table_info({table})")}
    return {row["column_name"] for row in conn.execute(
        "SELECT column_name FROM information_schema.columns "
        "WHERE table_schema=current_schema() AND table_name=%s", (table,),
    )}


def _lock_user_writes(conn):
    # Serialize the case-insensitive email check with concurrent user writes.
    if isinstance(conn, _SQLiteConnection):
        conn.execute("BEGIN IMMEDIATE")
    else:
        conn.execute("LOCK TABLE users IN SHARE ROW EXCLUSIVE MODE")


def init_db():
    with get_conn() as conn:
        initialize_schema(conn)


def initialize_schema(conn):
    """Create and upgrade the schema within the caller's transaction."""
    primary_key = (
        "INTEGER PRIMARY KEY AUTOINCREMENT" if isinstance(conn, _SQLiteConnection)
        else "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS users (
            id {primary_key},
            name TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            role TEXT NOT NULL CHECK (role IN ('pm', 'employee')),
            created_at TEXT NOT NULL
        )
    """)
    user_columns = _column_names(conn, "users")
    if "google_sub" not in user_columns:
        conn.execute("ALTER TABLE users ADD COLUMN google_sub TEXT")
    for column, definition in (
        ("job_title", "TEXT NOT NULL DEFAULT ''"),
        ("department", "TEXT NOT NULL DEFAULT ''"),
        ("google_email", "TEXT"),
        ("session_version", "INTEGER NOT NULL DEFAULT 0"),
        ("deleted_at", "TEXT"),
    ):
        if column not in user_columns:
            conn.execute(f"ALTER TABLE users ADD COLUMN {column} {definition}")
    conn.execute("UPDATE users SET google_email=email WHERE google_sub IS NOT NULL AND google_email IS NULL")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_users_google_sub ON users(google_sub)")
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS projects (
            id {primary_key},
            name TEXT NOT NULL,
            description TEXT,
            created_by INTEGER NOT NULL,
            created_at TEXT NOT NULL,
            FOREIGN KEY (created_by) REFERENCES users(id)
        )
    """)
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS project_members (
            project_id INTEGER NOT NULL,
            user_id INTEGER NOT NULL,
            PRIMARY KEY (project_id, user_id),
            FOREIGN KEY (project_id) REFERENCES projects(id),
            FOREIGN KEY (user_id) REFERENCES users(id)
        )
    """)
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS meetings (
            id {primary_key},
            title TEXT NOT NULL,
            transcript TEXT,
            summary TEXT,
            project_id INTEGER,
            created_by INTEGER NOT NULL,
            created_at TEXT NOT NULL,
            FOREIGN KEY (created_by) REFERENCES users(id),
            FOREIGN KEY (project_id) REFERENCES projects(id)
        )
    """)
    meeting_columns = _column_names(conn, "meetings")
    for column, definition in (
        ("recording_storage_path", "TEXT"),
        ("recording_filename", "TEXT"),
        ("recording_mime_type", "TEXT"),
        ("recording_file_size", "INTEGER"),
        ("recording_duration", "REAL"),
        ("meeting_minutes", "TEXT"),
    ):
        if column not in meeting_columns:
            conn.execute(f"ALTER TABLE meetings ADD COLUMN {column} {definition}")
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS decisions (
            id {primary_key},
            meeting_id INTEGER NOT NULL,
            decision TEXT NOT NULL,
            FOREIGN KEY (meeting_id) REFERENCES meetings(id)
        )
    """)
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS questions (
            id {primary_key},
            meeting_id INTEGER NOT NULL,
            question TEXT NOT NULL,
            FOREIGN KEY (meeting_id) REFERENCES meetings(id)
        )
    """)
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS action_items (
            id {primary_key},
            meeting_id INTEGER NOT NULL,
            task TEXT NOT NULL,
            owner_name TEXT,
            owner_user_id INTEGER,
            deadline TEXT,
            priority TEXT,
            evidence TEXT,
            status TEXT NOT NULL DEFAULT 'Pending',
            approved INTEGER NOT NULL DEFAULT 0,
            FOREIGN KEY (meeting_id) REFERENCES meetings(id),
            FOREIGN KEY (owner_user_id) REFERENCES users(id)
        )
    """)
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS followups (
            id {primary_key},
            action_item_id INTEGER NOT NULL,
            created_by INTEGER,
            recipient_user_id INTEGER,
            followup_type TEXT NOT NULL,
            message TEXT NOT NULL,
            created_at TEXT NOT NULL,
            sent_at TEXT,
            status TEXT NOT NULL DEFAULT 'Draft',
            employee_response TEXT,
            responded_at TEXT,
            FOREIGN KEY (action_item_id) REFERENCES action_items(id)
        )
    """)
    columns = _column_names(conn, "followups")
    for name, definition in (
        ("created_by", "INTEGER"),
        ("recipient_user_id", "INTEGER"),
        ("employee_response", "TEXT"),
        ("responded_at", "TEXT"),
    ):
        if name not in columns:
            conn.execute(f"ALTER TABLE followups ADD COLUMN {name} {definition}")
    conn.execute("CREATE INDEX IF NOT EXISTS idx_followups_recipient ON followups(recipient_user_id)")
    # Older follow-ups predate recipient/creator tracking. Adding the columns
    # alone leaves sent messages invisible to their employees' inboxes.
    # Fill only missing links so existing recipients and replies stay intact.
    conn.execute("""
        UPDATE followups
        SET recipient_user_id = (
            SELECT owner_user_id FROM action_items
            WHERE action_items.id = followups.action_item_id
        )
        WHERE recipient_user_id IS NULL
    """)
    conn.execute("""
        UPDATE followups
        SET created_by = (
            SELECT meetings.created_by FROM action_items
            JOIN meetings ON meetings.id = action_items.meeting_id
            WHERE action_items.id = followups.action_item_id
        )
        WHERE created_by IS NULL
    """)


