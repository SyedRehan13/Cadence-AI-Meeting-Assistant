def edit_meeting(meeting_id, data):
    with get_conn() as conn:
        meeting = conn.execute("SELECT transcript, meeting_minutes FROM meetings WHERE id=%s", (meeting_id,)).fetchone()
        if meeting["meeting_minutes"]:
            if data.transcript != meeting["transcript"]:
                raise ValueError("The transcript for generated meeting minutes cannot be edited without reanalysis")
            minutes = data.meeting_minutes.model_dump() if data.meeting_minutes else json.loads(meeting["meeting_minutes"])
            if data.meeting_minutes:
                for section in ("action_items", "dependencies_blockers_issues", "milestones"):
                    for number, item in enumerate(minutes[section], start=1):
                        item["ref_no"] = number
            else:
                minutes["meeting_summary"] = data.summary
            conn.execute("UPDATE meetings SET title=%s, summary=%s, meeting_minutes=%s WHERE id=%s",
                         (data.title, minutes["meeting_summary"], json.dumps(minutes, ensure_ascii=False), meeting_id))
        else:
            conn.execute("UPDATE meetings SET title=%s, summary=%s, transcript=%s WHERE id=%s",
                         (data.title, data.summary, data.transcript, meeting_id))
        conn.execute("DELETE FROM decisions WHERE meeting_id=%s", (meeting_id,))
        conn.execute("DELETE FROM questions WHERE meeting_id=%s", (meeting_id,))
        for value in data.decisions:
            if value.strip():
                conn.execute("INSERT INTO decisions (meeting_id, decision) VALUES (%s, %s)", (meeting_id, value.strip()))
        for value in data.questions:
            if value.strip():
                conn.execute("INSERT INTO questions (meeting_id, question) VALUES (%s, %s)", (meeting_id, value.strip()))


def delete_meeting(meeting_id, remove_recording):
    with get_conn() as conn:
        # Lock the meeting until its dependents and recording have been removed.
        if isinstance(conn, _SQLiteConnection):
            conn.execute("BEGIN IMMEDIATE")
            meeting = conn.execute("SELECT * FROM meetings WHERE id=%s", (meeting_id,)).fetchone()
        else:
            meeting = conn.execute("SELECT * FROM meetings WHERE id=%s FOR UPDATE", (meeting_id,)).fetchone()
        if not meeting:
            return
        conn.execute("DELETE FROM followups WHERE action_item_id IN (SELECT id FROM action_items WHERE meeting_id=%s)", (meeting_id,))
        for table in ("action_items", "decisions", "questions"):
            conn.execute(f"DELETE FROM {table} WHERE meeting_id=%s", (meeting_id,))
        conn.execute("DELETE FROM meetings WHERE id=%s", (meeting_id,))
        if meeting["recording_storage_path"]:
            remove_recording(meeting["recording_storage_path"])


