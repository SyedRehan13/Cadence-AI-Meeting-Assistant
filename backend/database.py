def create_google_user(name: str, email: str, subject: str, role: str):
    with get_conn() as conn:
        _lock_user_writes(conn)
        if conn.execute("SELECT 1 FROM users WHERE lower(email)=lower(%s)", (email,)).fetchone():
            raise sqlite3.IntegrityError("Account already exists")
        cur = conn.execute(
            """INSERT INTO users (name, email, password_hash, role, created_at, google_sub, google_email)
               VALUES (%s, %s, '', %s, %s, %s, %s) RETURNING id""",
            (name, email, role, datetime.now().isoformat(), subject, email),
        )
        return conn.execute("SELECT * FROM users WHERE id=%s", (cur.fetchone()["id"],)).fetchone()


def link_google_account(user_id: int, subject: str, google_email=None, expected_version=None):
    with get_conn() as conn:
        result = conn.execute(
            """UPDATE users SET google_sub=%s, google_email=COALESCE(%s, email), session_version=session_version+1
               WHERE id=%s AND google_sub IS NULL AND deleted_at IS NULL
               AND (CAST(%s AS INTEGER) IS NULL OR session_version=%s)""",
            (subject, google_email, user_id, expected_version, expected_version),
        )
        if result.rowcount != 1:
            raise sqlite3.IntegrityError("Google account already linked")


def update_user_profile(user_id: int, name: str, email: str, job_title: str, department: str, expected_version: int):
    with get_conn() as conn:
        _lock_user_writes(conn)
        if conn.execute(
            "SELECT 1 FROM users WHERE lower(email)=lower(%s) AND id != %s", (email, user_id),
        ).fetchone():
            raise sqlite3.IntegrityError("Email already in use")
        result = conn.execute(
            """UPDATE users SET name=%s, job_title=%s, department=%s,
               session_version=session_version + CASE WHEN email != %s THEN 1 ELSE 0 END, email=%s
               WHERE id=%s AND session_version=%s AND deleted_at IS NULL""",
            (name, job_title, department, email, email, user_id, expected_version),
        )
        if result.rowcount != 1:
            raise ValueError("Your account changed. Refresh and try again.")
        return conn.execute("SELECT * FROM users WHERE id=%s", (user_id,)).fetchone()


