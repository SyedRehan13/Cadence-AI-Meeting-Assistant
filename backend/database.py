def get_action_items(meeting_id: int = None, approved_only: bool = False, owner_user_id: int = None):
    query = """
        SELECT action_items.*, meetings.title AS meeting_title, meetings.project_id AS project_id,
                             projects.name AS project_name,
                             (SELECT employee_response FROM followups
                                WHERE followups.action_item_id = action_items.id
                                    AND employee_response IS NOT NULL
                                ORDER BY responded_at DESC LIMIT 1) AS employee_response,
                             (SELECT responded_at FROM followups
                                WHERE followups.action_item_id = action_items.id
                                    AND employee_response IS NOT NULL
                                ORDER BY responded_at DESC LIMIT 1) AS employee_responded_at
        FROM action_items
        LEFT JOIN meetings ON action_items.meeting_id = meetings.id
        LEFT JOIN projects ON meetings.project_id = projects.id
    """
    conditions, params = [], []
    if meeting_id is not None:
        conditions.append("action_items.meeting_id=%s")
        params.append(meeting_id)
    if approved_only:
        conditions.append("action_items.approved=1")
    if owner_user_id is not None:
        conditions.append("action_items.owner_user_id=%s")
        params.append(owner_user_id)
    if conditions:
        query += " WHERE " + " AND ".join(conditions)
    query += """ ORDER BY
        CASE action_items.priority WHEN 'High' THEN 0 WHEN 'Medium' THEN 1 ELSE 2 END,
        action_items.deadline"""
    with get_conn() as conn:
        return conn.execute(query, params).fetchall()


def get_overdue_items():
    today = date.today().isoformat()
    with get_conn() as conn:
        rows = conn.execute(
            "SELECT * FROM action_items WHERE approved=1 AND status != 'Completed'"
        ).fetchall()
    overdue = []
    for row in rows:
        try:
            d = datetime.fromisoformat(row["deadline"]).date().isoformat()
            if d < today:
                overdue.append(row)
        except (ValueError, TypeError):
            continue
    return overdue


def classify_action_item(item):
    """Classify an action item using stored deadline/status data only."""
    status = item["status"] or "Pending"
    if status == "Completed":
        return "Completed"

    if status.lower() == "at risk":
        return "At Risk"

    try:
        deadline = date.fromisoformat(item["deadline"])
    except (TypeError, ValueError):
        return None

    days_until_due = (deadline - date.today()).days
    if days_until_due < 0:
        return "Overdue"
    if days_until_due <= 3:
        return "Due Soon"
    return None


